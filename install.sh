#!/usr/bin/env bash
# Bootstrap this Mac rice from the dotfiles repo.
#   ./install.sh            install packages, link configs, start services
#   ./install.sh --dry-run  show what would happen, change nothing
#   ./install.sh --links    only (re)create symlinks
#   ./install.sh --dynamic-wallpaper   also build + set the solar dynamic topo wallpaper
set -euo pipefail

DOTFILES="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# Rebuild with: uv run wallpapers/topo_tallulah.py
WALLPAPER="$DOTFILES/wallpapers/topo-tallulah.png"
DRY=0; LINKS_ONLY=0; DYNAMIC_WALLPAPER=0
for arg in "$@"; do
    case "$arg" in
    --dry-run) DRY=1 ;;
    --links) LINKS_ONLY=1 ;;
    --dynamic-wallpaper) DYNAMIC_WALLPAPER=1 ;;
    *) echo "unknown option: $arg" >&2; exit 1 ;;
    esac
done

run() { if [ $DRY = 1 ]; then echo "  would run: $*"; else "$@"; fi; }
say() { printf '\033[38;2;140;159;130m==>\033[0m %s\n' "$*"; }

# target (in $HOME)            -> source (in repo)
LINKS=(
    ".zshrc"                     "zshrc"
    ".gitconfig"                 "gitconfig"
    ".config/starship.toml"      "starship.toml"
    ".config/ghostty"            "config/ghostty"
    ".config/sketchybar"         "config/sketchybar"
    ".config/hyprspace"          "config/hyprspace"
    ".config/borders"            "config/borders"
    ".config/bat"                "config/bat"
    ".config/eza"                "config/eza"
    ".config/btop"               "config/btop"
    ".config/fastfetch"          "config/fastfetch"
    ".config/lazygit"            "config/lazygit"
)

link_one() {  # link_one <absolute target> <absolute source> <label>
    local target="$1" source="$2" label="$3"
    if [ -L "$target" ] && [ "$(readlink "$target")" = "$source" ]; then
        echo "  ok      $label"
        return
    fi
    if [ -e "$target" ] || [ -L "$target" ]; then
        local backup="$target.backup.$(date +%Y%m%d%H%M%S)"
        echo "  backup  $label -> ${backup/#$HOME/~}"
        run mv "$target" "$backup"
    fi
    echo "  link    $label"
    run ln -s "$source" "$target"
}

# Zen keeps its active profile in profiles.ini ([Install…] Default=, else Default=1)
zen_profile() {
    local root="$HOME/Library/Application Support/zen" rel
    [ -f "$root/profiles.ini" ] || return 1
    rel="$(awk -F= '/^\[Install/{i=1} i && /^Default=/{print $2; exit}' "$root/profiles.ini")"
    [ -z "$rel" ] && rel="$(awk -F= '/^Path=/{p=$2} /^Default=1/{print p; exit}' "$root/profiles.ini")"
    [ -n "$rel" ] && echo "$root/$rel"
}

link_zen() {
    local profile
    if ! profile="$(zen_profile)"; then
        echo "  skip    Zen (no profile yet — launch Zen once, then rerun with --links)"
        return
    fi
    copy_zen_chrome "$profile/chrome"
    write_zen_userjs "$profile/user.js"
}

# Zen ignores userContent.css when it's a symlink (file or folder) — web content
# is rendered in sandboxed processes — so copy the stylesheets in instead.
# Rerun `./install.sh --links` after editing config/zen/chrome/*.css.
copy_zen_chrome() {
    local dir="$1" f
    if [ -L "$dir" ]; then
        echo "  unlink  Zen chrome/ (was a symlink)"
        run rm "$dir"
    fi
    run mkdir -p "$dir"
    for f in userChrome.css userContent.css; do
        if [ -f "$dir/$f" ] && cmp -s "$DOTFILES/config/zen/chrome/$f" "$dir/$f"; then
            echo "  ok      Zen chrome/$f"
        else
            echo "  copy    Zen chrome/$f"
            run cp "$DOTFILES/config/zen/chrome/$f" "$dir/$f"
        fi
    done
}

# user.js can't read env files, so build it: repo prefs + private start page URL
write_zen_userjs() {
    local target="$1" marker="// generated by dotfiles install.sh"
    if [ -e "$target" ] && [ ! -L "$target" ] && ! head -1 "$target" | grep -qF "$marker"; then
        echo "  backup  Zen user.js -> user.js.backup.$(date +%Y%m%d%H%M%S)"
        run mv "$target" "$target.backup.$(date +%Y%m%d%H%M%S)"
    fi
    [ -L "$target" ] && run rm "$target"
    echo "  write   Zen user.js (+ start page from private/homelab.env)"
    [ $DRY = 1 ] && return
    {
        echo "$marker — edit config/zen/user.js instead"
        cat "$DOTFILES/config/zen/user.js"
        if [ -f "$DOTFILES/private/homelab.env" ]; then
            # shellcheck source=/dev/null
            . "$DOTFILES/private/homelab.env"
            echo "user_pref(\"browser.startup.homepage\", \"${STARTPAGE_URL:-$HOMEPAGE_URL}\");"
        fi
    } > "$target"
}

ensure_private() {
    if [ ! -f "$DOTFILES/private/homelab.env" ]; then
        echo "  create  private/homelab.env from private.example (fill in your addresses)"
        run mkdir -p "$DOTFILES/private"
        run cp "$DOTFILES/private.example/homelab.env" "$DOTFILES/private/homelab.env"
    fi
}

link_all() {
    say "Linking configs"
    ensure_private
    run mkdir -p "$HOME/.config"
    local i target source
    for ((i = 0; i < ${#LINKS[@]}; i += 2)); do
        target="$HOME/${LINKS[i]}"; source="$DOTFILES/${LINKS[i + 1]}"
        if [ -L "$target" ] && [ "$(readlink "$target")" = "$source" ]; then
            echo "  ok      ~/${LINKS[i]}"
            continue
        fi
        if [ -e "$target" ] || [ -L "$target" ]; then
            local backup="$target.backup.$(date +%Y%m%d%H%M%S)"
            echo "  backup  ~/${LINKS[i]} -> ${backup/#$HOME/~}"
            run mv "$target" "$backup"
        fi
        echo "  link    ~/${LINKS[i]} -> ${LINKS[i + 1]}"
        run ln -s "$source" "$target"
    done
    link_zen
}

if [ $LINKS_ONLY = 1 ]; then link_all; exit 0; fi

if ! command -v brew >/dev/null 2>&1; then
    say "Homebrew is not installed — install it from https://brew.sh first"
    exit 1
fi

say "Installing packages from Brewfile"
run brew bundle --file="$DOTFILES/Brewfile"

link_all

say "Starting services"
run brew services start sketchybar
run brew services start borders

say "Installing VS Code Severance theme"
run python3 "$DOTFILES/config/vscode/install-theme.py"

if [ $DYNAMIC_WALLPAPER = 1 ]; then
    # Generated, gitignored (~45 MB): 18 frames whose hillshade follows the real sun
    say "Building solar dynamic wallpaper (first run downloads lidar + builds wallpapper)"
    run uv run --python 3.12 "$DOTFILES/wallpapers/topo_tallulah.py" --dynamic
    WALLPAPER="$DOTFILES/wallpapers/topo-tallulah-dynamic.heic"
fi

say "Setting wallpaper"
run osascript -e "tell application \"System Events\" to set picture of every desktop to POSIX file \"$WALLPAPER\""

say "Done. Manual steps:"
cat <<'STEPS'
  1. Open Hyprspace and grant Accessibility (System Settings → Privacy & Security).
  2. System Settings → Control Center → Automatically hide and show the menu bar: Always.
  3. System Settings → Trackpad → More Gestures → Swipe between full-screen apps: Four Fingers.
  4. BetterTouchTool (Setapp) → Presets → Import config/bettertouchtool/hyprspace-swipes.bttpreset
STEPS
